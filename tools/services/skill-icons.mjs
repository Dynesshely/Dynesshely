/**
 * skill-icons - https://github.com/LelouchFR/skill-icons
 *
 * Upstream is a Netlify/Vercel style Go service: `api/index.go` holds the HTTP
 * handler (package `handler`) and its data is generated at "build" time by
 * `build.go`, which inlines every `assets/*.svg` into a single `iconsJSON`
 * string literal on line 18 of `api/index.go` *in place*. That means building
 * it inside `vendor/` would dirty the checkout, so `prepare()` works on a copy
 * under `.build/skill-icons/`.
 *
 * The upstream Dockerfile turns `api/index.go` into a `package main` with sed
 * and deletes the `init()`/`Handler()` bits. We keep the vendored file intact
 * instead and add a tiny `cmd/server/main.go` that serves the exported
 * `handler.Handler` through net/http - same routes, no text surgery.
 */
import fs from "node:fs/promises";
import path from "node:path";
import { killTree, runCommand, spawnService, waitForHttp } from "../lib/proc.mjs";

/**
 * The little HTTP front end. `api` exports `Handler` (Netlify/Vercel style) and
 * wires up gin's `/api` group in its `init()`, so all we do is listen on it.
 * The listen address comes from argv[1] / SKILL_ICONS_ADDR / a loopback default.
 */
const SERVER_SOURCE = `// Generated by tools/services/skill-icons.mjs - do not edit the copy under .build/.
package main

import (
	"log"
	"net/http"
	"os"
	"strings"

	handler "github.com/lelouchfr/skill-icons/api"
)

func listenAddress() string {
	if len(os.Args) > 1 && os.Args[1] != "" {
		return os.Args[1]
	}
	if addr := os.Getenv("SKILL_ICONS_ADDR"); addr != "" {
		return addr
	}
	return "127.0.0.1:8080"
}

func main() {
	addr := listenAddress()
	if !strings.Contains(addr, ":") {
		addr = "127.0.0.1:" + addr
	}

	mux := http.NewServeMux()
	mux.HandleFunc("/", handler.Handler)

	log.Printf("skill-icons listening on http://%s/api/icons", addr)
	if err := (&http.Server{Addr: addr, Handler: mux}).ListenAndServe(); err != nil {
		log.Fatalf("skill-icons: %v", err)
	}
}
`;

const goExe = () => "go";
const workDir = (ctx) => path.join(ctx.buildDir, "skill-icons");
const binaryPath = (ctx) =>
  path.join(workDir(ctx), "bin", process.platform === "win32" ? "skill-icons.exe" : "skill-icons");

let child = null;
let baseUrl = null;

export default {
  id: "skill-icons",
  port: 4706,
  get child() {
    return child;
  },

  async prepare(ctx) {
    const startedAt = Date.now();
    const source = path.join(ctx.vendorDir, "skill-icons");
    const work = workDir(ctx);

    // build.go rewrites api/index.go in place, so always start from a clean copy
    // of the pristine vendored tree - vendor/ itself is never touched.
    await fs.rm(work, { recursive: true, force: true });
    await fs.mkdir(path.dirname(work), { recursive: true });
    await fs.cp(source, work, { recursive: true });
    ctx.log(`copied vendor/skill-icons -> .build/skill-icons (${Date.now() - startedAt}ms)`);

    // 1. vendor the module's dependencies (gin) into the shared module cache.
    const downloadStart = Date.now();
    await runCommand("skill-icons:go", goExe(), ["mod", "download"], { cwd: work, log: ctx.log });
    ctx.log(`go mod download finished in ${Date.now() - downloadStart}ms`);

    // 2. inline assets/*.svg into api/index.go via upstream's unmodified build.go.
    const inlineStart = Date.now();
    await runCommand("skill-icons:go", goExe(), ["run", "build.go"], { cwd: work, log: ctx.log });
    ctx.log(`inlined assets/*.svg into api/index.go (${Date.now() - inlineStart}ms)`);

    // 3. drop in the net/http entry point (kept out of vendor/ on purpose).
    const cmdDir = path.join(work, "cmd", "server");
    await fs.mkdir(cmdDir, { recursive: true });
    await fs.writeFile(path.join(cmdDir, "main.go"), SERVER_SOURCE, "utf8");

    // 4. build a static-ish binary under .build/skill-icons/bin/.
    const buildStart = Date.now();
    await runCommand(
      "skill-icons:go",
      goExe(),
      ["build", "-trimpath", "-ldflags=-s -w", "-o", binaryPath(ctx), "./cmd/server"],
      { cwd: work, env: { CGO_ENABLED: "0" }, log: ctx.log },
    );
    const { size } = await fs.stat(binaryPath(ctx));
    ctx.log(
      `built .build/skill-icons/bin/skill-icons in ${Date.now() - buildStart}ms (${(size / 1024 / 1024).toFixed(1)} MB)`,
    );
    ctx.log(`prepare finished in ${Date.now() - startedAt}ms`);
  },

  async start(ctx) {
    const bin = binaryPath(ctx);
    await fs.access(bin); // fail loudly if prepare() did not run

    child = spawnService("skill-icons", bin, [String(ctx.port)], {
      log: ctx.log,
      env: { GIN_MODE: "release" },
    });
    baseUrl = `http://127.0.0.1:${ctx.port}`;
    // First hit also parses the inlined ~10 MB icons JSON, so allow some slack.
    await waitForHttp(`${baseUrl}/api/icons?i=js`, { timeoutMs: 120_000, label: "skill-icons" });
    return baseUrl;
  },

  async stop() {
    await killTree(child);
    child = null;
  },
};
